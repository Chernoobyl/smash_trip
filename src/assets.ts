export type SpriteId = keyof typeof ASSETS;

export type SpriteCategory =
  | "logo"
  | "brutus"
  | "nika"
  | "volt"
  | "dummy"
  | "weapons"
  | "boosters"
  | "fx"
  | "collectibles"
  | "backgrounds"
  | "environment";

export interface SpriteInfo {
  id: SpriteId;
  category: SpriteCategory;
  name: string;
  filePath: string;
}

function getCategoryFromPath(filePath: string): SpriteCategory {
  if (filePath.includes("/logo/")) return "logo";
  if (filePath.includes("/brutus/")) return "brutus";
  if (filePath.includes("/nika/")) return "nika";
  if (filePath.includes("/volt/")) return "volt";
  if (filePath.includes("/dummy/")) return "dummy";
  if (filePath.includes("/weapons/")) return "weapons";
  if (filePath.includes("/boosters/")) return "boosters";
  if (filePath.includes("/fx/")) return "fx";
  if (filePath.includes("/collectibles/")) return "collectibles";
  if (filePath.includes("/backgrounds/")) return "backgrounds";
  if (filePath.includes("/environment/")) return "environment";
  return "environment";
}

/**
 * Manifest for all individual PNG sprites
 */
export const SPRITE_MANIFEST: Record<SpriteId, SpriteInfo> = Object.entries(ASSETS).reduce(
  (acc, [id, filePath]) => {
    const key = id as SpriteId;
    const category = getCategoryFromPath(filePath);
    acc[key] = {
      id: key,
      category,
      name: key.replace(/_/g, " "),
      filePath,
    };
    return acc;
  },
  {} as Record<SpriteId, SpriteInfo>
);

